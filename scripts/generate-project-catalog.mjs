#!/usr/bin/env node

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createJiti } from 'jiti';
import { format } from 'prettier';

const jiti = createJiti(import.meta.url);
const { appCatalog } = await jiti.import('../packages/tooling/src/setup/catalog.ts');

const workspaceRoot = resolve(import.meta.dirname, '..');
const catalogPath = resolve(workspaceRoot, 'docs/project-catalog.md');
const ignoredDirectories = new Set([
  '.cache',
  '.git',
  '.nx',
  'coverage',
  'dist',
  'node_modules',
  'playwright-report',
  'test-results',
  'tmp',
]);

export function collectApplicationRoots(root) {
  const projects = new Map();

  function visit(directory) {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      const path = resolve(directory, entry.name);
      if (entry.isDirectory()) {
        visit(path);
        continue;
      }
      if (entry.name !== 'project.json') continue;

      const project = JSON.parse(readFileSync(path, 'utf8'));
      if (project.projectType !== 'application' || typeof project.name !== 'string') continue;
      if (projects.has(project.name)) throw new Error(`Duplicate Nx application name: ${project.name}`);
      projects.set(project.name, relative(root, dirname(path)).replaceAll('\\', '/'));
    }
  }

  visit(resolve(root, 'apps'));
  return projects;
}

export function renderProjectCatalog(catalog, projectRoots) {
  const entries = Object.values(catalog);
  const catalogIds = new Set(entries.map((entry) => entry.id));

  for (const entry of entries) {
    if (!projectRoots.has(entry.id)) {
      throw new Error(`Setup catalog app is missing an Nx application: ${entry.id}`);
    }
  }
  for (const projectName of projectRoots.keys()) {
    if (!catalogIds.has(projectName)) {
      throw new Error(`Nx application is missing from the setup catalog: ${projectName}`);
    }
  }

  const sections = [
    ['Frontend applications', 'frontend'],
    ['Backend applications', 'backend'],
    ['End-to-end projects', 'e2e'],
  ];
  const lines = [
    '<!-- Generated by scripts/generate-project-catalog.mjs. Do not edit by hand. -->',
    '',
    '# Project catalog',
    '',
    'This is the canonical human-readable map of selectable applications. It is',
    'generated from the executable setup catalog and each Nx `project.json`; run',
    '`pnpm run docs:catalog` after changing either source.',
    '',
    'No application is the monorepo default. `pnpm nrb setup` records an explicit',
    'selection in `.nrb/workspace.json`, and it can be rerun to add or remove apps.',
    '',
  ];

  for (const [heading, platform] of sections) {
    lines.push(`## ${heading}`, '');
    lines.push('| ID | Nx project root | Runtime | Class | Template hostname | Required selection |');
    lines.push('| --- | --- | --- | --- | --- | --- |');
    for (const entry of entries.filter((candidate) => candidate.platform === platform)) {
      const requirements = [
        ...entry.requiresApps.map((id) => `\`${id}\``),
        ...entry.requiresCapabilities.map((id) => `\`${id}\` capability`),
      ];
      lines.push(
        `| \`${entry.id}\` | \`${projectRoots.get(entry.id)}\` | ${entry.runtime} | ${capitalize(entry.classification)} | ${entry.publicHostname ? `\`${entry.publicHostname}\`` : 'Not deployable'} | ${requirements.length > 0 ? requirements.join(', ') : 'None'} |`,
      );
    }
    lines.push('');
  }

  lines.push(
    '## Domain ownership',
    '',
    '`landing-app` owns `example.com` in the uninitialized template. During product',
    'initialization, explicitly choose either `landing-app` or `site-app` for the',
    'real apex. Every other public application keeps `<app-id>.<base-domain>`;',
    'for example, `auth-app-api` maps to `auth-app-api.example.com`.',
    '',
    'Deployment guides describe how to route one-domain and per-app-domain',
    'topologies; they do not maintain another application/hostname table.',
    '',
    '## Library identities and paths',
    '',
    'Do not maintain an exhaustive library table in Markdown. Library identity is',
    'owned by its `project.json`, while public TypeScript aliases are owned by',
    '`tsconfig.base.json`. The stable placement rules are:',
    '',
    '| Boundary | Project-root convention |',
    '| --- | --- |',
    '| Backend common | `libs/backend/common/<name>/lib` |',
    '| Backend feature | `libs/backend/feature/<scope>/<layer>/lib` |',
    '| Backend PostgreSQL | `libs/backend/postgres/main/<scope>/lib` |',
    '| Frontend | `libs/frontend/<scope-or-name>/lib` |',
    '| Cross-runtime common | `libs/common/<scope-or-name>/lib` |',
    '',
    'Use the live graph instead of copying project metadata into another document:',
    '',
    '```bash',
    'pnpm exec nx show projects',
    'pnpm exec nx show project <id>',
    '```',
    '',
    'Local project READMEs own only project-specific responsibilities, commands, and',
    'completion notes. See the [service port registry](PORTS.md) for local and',
    'staging ports, and the [scaffolding contract](scaffolding-and-extension.md) for',
    'adding or registering ownership.',
    '',
    '## Authority rules',
    '',
    '- Selectable app metadata, dependencies, classification, runtime, and template hostnames: `packages/tooling/src/setup/catalog.ts`.',
    "- Nx identity, source root, tags, and targets: the project's `project.json`.",
    '- Public import aliases: `tsconfig.base.json`.',
    '- Local and staging ports: [Service Port Registry](PORTS.md).',
    '- Project-specific behavior and commands: the nearest `README.md` and `AGENTS.md`.',
    '',
  );

  return lines.join('\n');
}

export function findCopiedCatalogRows(root, catalog, projectRoots, markdownFiles = collectMarkdownFiles(root)) {
  const failures = [];
  for (const filePath of markdownFiles) {
    if (resolve(filePath) === resolve(root, 'docs/project-catalog.md')) continue;
    if (resolve(filePath) === resolve(root, 'CHANGELOG.md')) continue;
    const lines = readFileSync(filePath, 'utf8').split(/\r?\n/u);
    for (const entry of Object.values(catalog)) {
      const id = `\`${entry.id}\``;
      const projectRoot = `\`${projectRoots.get(entry.id)}\``;
      const hostname = entry.publicHostname ? `\`${entry.publicHostname}\`` : null;
      for (const [index, line] of lines.entries()) {
        if (line.includes(id) && (line.includes(projectRoot) || (hostname && line.includes(hostname)))) {
          failures.push(
            `${relative(root, filePath).replaceAll('\\', '/')}:${index + 1}: copied project catalog row for ${entry.id}`,
          );
        }
      }
    }
  }
  return failures;
}

function collectMarkdownFiles(root) {
  const files = [];
  function visit(directory) {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      if (entry.isDirectory() && ignoredDirectories.has(entry.name)) continue;
      const path = resolve(directory, entry.name);
      if (entry.isDirectory()) visit(path);
      else if (entry.isFile() && entry.name.endsWith('.md')) files.push(path);
    }
  }
  visit(root);
  return files;
}

function capitalize(value) {
  return value.charAt(0).toUpperCase() + value.slice(1);
}

async function main() {
  const projectRoots = collectApplicationRoots(workspaceRoot);
  const rendered = await format(renderProjectCatalog(appCatalog, projectRoots), {
    filepath: catalogPath,
  });
  if (process.argv.includes('--check')) {
    if (!existsSync(catalogPath) || readFileSync(catalogPath, 'utf8') !== rendered) {
      process.stderr.write('docs/project-catalog.md is stale; run pnpm run docs:catalog.\n');
      process.exitCode = 1;
      return;
    }
    const copiedRows = findCopiedCatalogRows(workspaceRoot, appCatalog, projectRoots);
    if (copiedRows.length > 0) {
      process.stderr.write(`Copied project catalog data found:\n${copiedRows.map((row) => `- ${row}`).join('\n')}\n`);
      process.exitCode = 1;
      return;
    }
    process.stdout.write('Project catalog is current.\n');
    return;
  }

  writeFileSync(catalogPath, rendered);
  process.stdout.write('Generated docs/project-catalog.md.\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
