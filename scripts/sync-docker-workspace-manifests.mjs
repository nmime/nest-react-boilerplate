#!/usr/bin/env node
/**
 * Keep Docker's dependency-only context in sync with workspace package files.
 *
 * Docker can then run `pnpm install` before copying source code, allowing a
 * source-only change to reuse the dependency layer across every image target.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const destinationRoot = join(rootDir, 'docker', 'workspace-manifests');
const sourceRoots = ['apps', 'libs', 'packages'];
const ignoredDirectories = new Set(['.git', '.nx', 'coverage', 'dist', 'node_modules']);
const generatedHeader = '# Generated by `pnpm run docker:manifests:sync`; do not edit.\n';

const listPackageManifests = (directory) => {
  const found = [];
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (!ignoredDirectories.has(entry.name)) found.push(...listPackageManifests(join(directory, entry.name)));
      continue;
    }
    if (entry.isFile() && entry.name === 'package.json') found.push(join(directory, entry.name));
  }
  return found;
};

const expectedFiles = () =>
  sourceRoots
    .flatMap((sourceRoot) => listPackageManifests(join(rootDir, sourceRoot)))
    .sort()
    .map((absolutePath) => ({
      content: readFileSync(absolutePath, 'utf8'),
      relativePath: relative(rootDir, absolutePath),
    }));

const listDestinationManifests = (directory) => {
  if (!existsSync(directory)) return [];
  const found = [];
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const absolutePath = join(directory, entry.name);
    if (entry.isDirectory()) found.push(...listDestinationManifests(absolutePath));
    else if (entry.isFile() && entry.name === 'package.json') found.push(relative(destinationRoot, absolutePath));
  }
  return found.sort();
};

const assertSynchronized = () => {
  const expected = expectedFiles();
  const expectedPaths = expected.map(({ relativePath }) => relativePath);
  const actualPaths = listDestinationManifests(destinationRoot);
  const problems = [];
  if (JSON.stringify(actualPaths) !== JSON.stringify(expectedPaths)) {
    problems.push(`manifest paths differ (expected ${expectedPaths.length}, found ${actualPaths.length})`);
  }
  for (const { content, relativePath } of expected) {
    const destination = join(destinationRoot, relativePath);
    if (!existsSync(destination) || readFileSync(destination, 'utf8') !== content) {
      problems.push(`stale or missing ${relativePath}`);
    }
  }
  const readmePath = join(destinationRoot, 'README.md');
  if (!existsSync(readmePath) || readFileSync(readmePath, 'utf8') !== generatedHeader) {
    problems.push('missing generated README.md');
  }
  if (problems.length > 0) {
    throw new Error(
      `Docker workspace manifests are out of date: ${problems.join('; ')}. Run pnpm run docker:manifests:sync.`,
    );
  }
  console.log(`Docker workspace manifests are synchronized (${expected.length} package files).`);
};

const synchronize = () => {
  const expected = expectedFiles();
  const expectedPaths = new Set(expected.map(({ relativePath }) => relativePath));
  for (const existing of listDestinationManifests(destinationRoot)) {
    if (!expectedPaths.has(existing)) rmSync(join(destinationRoot, existing));
  }
  for (const { content, relativePath } of expected) {
    const destination = join(destinationRoot, relativePath);
    mkdirSync(dirname(destination), { recursive: true });
    writeFileSync(destination, content);
  }
  mkdirSync(destinationRoot, { recursive: true });
  writeFileSync(join(destinationRoot, 'README.md'), generatedHeader);
  console.log(`Synchronized Docker workspace manifests (${expected.length} package files).`);
};

try {
  if (process.argv.length === 3 && process.argv[2] === '--check') assertSynchronized();
  else if (process.argv.length === 2) synchronize();
  else throw new Error('Usage: node scripts/sync-docker-workspace-manifests.mjs [--check]');
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
}
